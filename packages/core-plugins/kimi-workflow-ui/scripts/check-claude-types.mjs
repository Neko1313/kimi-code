import { execFileSync } from 'node:child_process';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

const declarations = process.argv[2] ?? process.env['CLAUDE_MOD_TYPES'];
if (!declarations) throw new Error('Pass the claude-code/index.d.ts generated by /plugin-types, or set CLAUDE_MOD_TYPES');
const plugin = path.resolve(import.meta.dirname, '..');
const repository = path.resolve(plugin, '../../..');
const temporary = await mkdtemp(path.join(tmpdir(), 'kimi-mods-types-'));
try {
  const config = path.join(temporary, 'tsconfig.json');
  await writeFile(config, JSON.stringify({
    extends: path.join(repository, 'tsconfig.json'),
    compilerOptions: { noEmit: true, skipLibCheck: true, typeRoots: [path.join(repository, 'node_modules/@types')], paths: { 'claude-code': [path.resolve(declarations)] } },
    include: [path.join(plugin, 'runtime/view.ts'), path.join(plugin, '../kimi-workflow/types')],
  }));
  execFileSync('pnpm', ['exec', 'tsc', '-p', config, '--noEmit'], { cwd: repository, stdio: 'inherit' });
} finally { await rm(temporary, { recursive: true, force: true }); }
